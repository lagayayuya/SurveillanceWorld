"""`lacarte calibrate`: optical distributions per camera type and generation, from the
catalogue (catalogue/models.csv), written into rules/optics.yaml (`distributions`).

Per type and generation: 10th, 50th and 90th percentiles of the horizontal resolution and
of the horizontal field of view. A varifocal model counts over its range (five log-spaced
settings, one fifth of a model each: how it is set on site is unknown). PTZ cameras fill
their wide-angle field; their tele end is kept apart for the zoomed-reach outline. A cell
with fewer than `min_models` models falls back to the type over all generations; a type
with fewer than that keeps its provisional market range (`provisional_kinds`).
"""

from __future__ import annotations

import csv
import math
from datetime import date
from pathlib import Path

import numpy as np

from lacarte import optics, regions

CATALOGUE = regions.ROOT / "catalogue" / "models.csv"
RULES = regions.ROOT / "rules" / "optics.yaml"
MARKER = "# --- generated by `lacarte calibrate`"
VARIFOCAL_SETTINGS = 5
QUANTILES = (0.1, 0.5, 0.9)


def generation_of(year: int, generations: dict[str, list]) -> str:
    for name, (first, last) in generations.items():
        if (first is None or year >= first) and (last is None or year <= last):
            return name
    raise ValueError(f"no generation for {year}")


def model_points(row: dict) -> tuple[float, list[tuple[float, float]], float | None]:
    """-> (resolution, [(filled hfov, weight)], tele hfov for PTZ or None)."""
    res = float(row["resolution_px"])
    lo, hi = float(row["hfov_min_deg"]), float(row["hfov_max_deg"])
    if row["kind"] in ("ptz", "panorama") or math.isclose(lo, hi):
        tele = lo if row["kind"] == "ptz" else None
        return res, [(hi, 1.0)], tele
    settings = np.geomspace(lo, hi, VARIFOCAL_SETTINGS)
    return res, [(float(f), 1.0 / VARIFOCAL_SETTINGS) for f in settings], None


def weighted_quantiles(values, weights, qs=QUANTILES) -> list[float]:
    """Quantiles of a weighted sample (linear between cumulative-weight midpoints)."""
    order = np.argsort(values)
    v = np.asarray(values, dtype=float)[order]
    w = np.asarray(weights, dtype=float)[order]
    cum = (np.cumsum(w) - w / 2) / w.sum()
    return [float(np.interp(q, cum, v)) for q in qs]


def summarise(rows: list[dict]) -> dict:
    res, res_w, fov, fov_w, tele = [], [], [], [], []
    for row in rows:
        r, fills, t = model_points(row)
        res.append(r)
        res_w.append(1.0)
        for f, w in fills:
            fov.append(f)
            fov_w.append(w)
        if t is not None:
            tele.append(t)
    out = {
        "models": len(rows),
        "resolution_px": [round(x) for x in weighted_quantiles(res, res_w)],
        "hfov_deg": [round(x, 1) for x in weighted_quantiles(fov, fov_w)],
    }
    if tele:
        out["tele_hfov_deg"] = [round(x, 2) for x in weighted_quantiles(tele, [1.0] * len(tele))]
    return out


def usable(row: dict) -> bool:
    return all(row[c] != "" for c in ("resolution_px", "hfov_min_deg", "hfov_max_deg"))


def distributions(rows: list[dict], cal: dict, provisional: dict) -> dict:
    gens = cal["generations"]
    need = cal["min_models"]
    out = {}
    for kind in sorted({r["kind"] for r in rows} | set(provisional)):
        mine = [r for r in rows if r["kind"] == kind and usable(r)]
        if len(mine) < need:
            p = provisional[kind]
            pooled = {
                "models": len(mine),
                "source": "provisional market range, too few catalogue models",
                "resolution_px": _range_as_percentiles(p["resolution_px"], 0),
                "hfov_deg": _range_as_percentiles(p["hfov_deg"], 1),
            }
            if "tele_hfov_deg" in p:
                pooled["tele_hfov_deg"] = _range_as_percentiles(p["tele_hfov_deg"], 2)
            out[kind] = {"pooled": pooled}
            continue
        entry = {"pooled": summarise(mine), "generations": {}}
        for g in gens:
            cell = [r for r in mine if generation_of(int(r["release_year"]), gens) == g]
            if len(cell) >= need:
                entry["generations"][g] = summarise(cell)
            else:
                entry["generations"][g] = {"models": len(cell), "use": "pooled"}
                if g in cal.get("default_generations", []):
                    entry["generations"][g]["certainty"] = "default"
        out[kind] = entry
    return out


def _range_as_percentiles(bounds: list[float], digits: int) -> list[float]:
    """A provisional [low, high] range read as p10 / geometric centre / p90."""
    lo, hi = bounds
    return [lo, round(math.sqrt(lo * hi), digits), hi]


def load(path: Path = CATALOGUE) -> list[dict]:
    with path.open(newline="") as fh:
        return list(csv.DictReader(fh))


def render(dist: dict, today: date) -> str:
    """The generated block of rules/optics.yaml."""
    import yaml

    head = (
        f"{MARKER} from catalogue/models.csv on {today.isoformat()}; do not edit by hand ---\n"
        "# Per type and generation: models used, then [p10, p50, p90] of the horizontal\n"
        "# resolution (px) and of the horizontal field of view (deg; PTZ: wide end, tele end\n"
        "# apart). `use: pooled` = too few models in the cell, the type's pooled values apply;\n"
        "# `certainty: default` = estimated by default (calibration.default_generations).\n"
    )
    body = yaml.safe_dump(
        {"distributions": dist},
        sort_keys=False,
        allow_unicode=True,
        width=100,
        default_flow_style=None,
    )
    return head + body


def run() -> dict:
    import yaml

    text = RULES.read_text()
    hand = text.split(MARKER)[0].rstrip() + "\n\n"
    rules = yaml.safe_load(hand)
    dist = distributions(load(), rules["calibration"], rules["provisional_kinds"])
    RULES.write_text(hand + render(dist, date.today()))
    optics.rules.cache_clear()
    optics.samples.cache_clear()
    return dist
